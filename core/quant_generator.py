def generate_quant_project(
    request: RunRequest,
    parent_dir: str | Path,
    progress: Callable[[str], None] | None = None,
) -> QuantProject:
    progress = progress or (lambda _message: None)
    progress("加载当前策略行情并生成信号 ...")
    output = execute(request, progress=progress)
    if output.bars is None or output.bars.empty:
        raise ValueError("当前策略没有可导出的行情数据")
    parent = Path(parent_dir).expanduser()
    parent.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    strategy_slug = _safe_slug(output.strategy_meta.slug)
    symbol_slug = _safe_slug(output.symbol)
    project_dir = parent / f"akquant_{strategy_slug}_{symbol_slug}_{stamp}"
    project_dir.mkdir(parents=True, exist_ok=False)
    (project_dir / "data").mkdir()
    (project_dir / "quant_app").mkdir()
    (project_dir / "output").mkdir()
    bars = output.bars.copy()
    bars["date"] = pd.to_datetime(bars["date"]).dt.strftime("%Y-%m-%d")
    bars["symbol"] = output.symbol
    bars = bars[["date", "open", "high", "low", "close", "volume", "amount", "symbol"]]
    bars.to_csv(project_dir / "data" / "bars.csv", index=False, encoding="utf-8")
    signals = output.result.signals.copy()
    if "date" not in signals.columns:
        signals = signals.reset_index().rename(columns={"index": "date"})
    signals["date"] = pd.to_datetime(signals["date"]).dt.strftime("%Y-%m-%d")
    for column in ("entry", "exit"):
        signals[column] = signals[column].fillna(False).astype(bool)
    signals = signals[["date", "entry", "exit", "score", "entry_reason", "exit_reason"]]
    signals.to_csv(project_dir / "data" / "signals.csv", index=False, encoding="utf-8")
    config = {
        "generated_by": "股票策略工坊",
        "generator_version": TEMPLATE_VERSION,
        "engine": f"akquant=={AKQUANT_VERSION}",
        "strategy": {
            "slug": output.strategy_meta.slug,
            "name": output.strategy_meta.name,
            "description": output.strategy_meta.description,
            "params": request.strategy_params,
            "model": output.model_meta.slug if output.model_meta else None,
        },
        "symbol": output.symbol,
        "start": str(output.result.metrics.get("start", request.start)),
        "end": str(output.result.metrics.get("end", request.end)),
        "adjust": request.trade_adjust,
        "benchmark_symbol": request.benchmark_symbol,
        "initial_cash": float(request.config.initial_cash),
        "commission_rate": float(request.config.commission_rate),
        "stamp_tax_rate": float(request.config.stamp_tax_rate),
        "transfer_fee_rate": float(request.config.transfer_fee_rate),
        "min_commission": float(request.config.min_commission),
        "slippage_bps": float(request.config.slippage_bps),
        "lot_size": int(request.config.lot_size),
        "position_pct": float(request.config.position_pct),
        "close_at_end": bool(request.config.close_at_end),
        "signal_semantics": "T close signal -> AKQuant next bar execution",
        "reference_metrics": output.result.metrics,
        "warnings": output.warnings,
    }
    _write_text(project_dir / "config.json", json.dumps(config, ensure_ascii=False, indent=2, default=str))
    _write_text(project_dir / "quant_app" / "__init__.py", '"""Generated AKQuant project."""\n')
    _write_text(project_dir / "quant_app" / "strategy.py", _strategy_template())
    _write_text(project_dir / "quant_app" / "backtest.py", _backtest_template())
    _write_text(project_dir / "requirements.txt", f"akquant=={AKQUANT_VERSION}\\npandas>=2.2\\nnumpy>=1.26\\n")
    _write_text(project_dir / "run.sh", _run_template())
    try:
        (project_dir / "run.sh").chmod(0o755)
    except OSError:
        pass
    _write_text(project_dir / "README.md", _readme_template())
    reference = project_dir / "reference"
    reference.mkdir()
    output.result.trades.to_csv(reference / "reference_trades.csv", index=False, encoding="utf-8-sig")
    _write_text(reference / "reference_metrics.json", json.dumps(output.result.metrics, ensure_ascii=False, indent=2, default=str))
    files = sorted(str(path.relative_to(project_dir)) for path in project_dir.rglob("*") if path.is_file())
    progress(f"量化项目已生成: {project_dir} ({len(files)} 个文件)")
    return QuantProject(
        path=project_dir,
        strategy_name=output.strategy_meta.name,
        symbol=output.symbol,
        start=str(config["start"]),
        end=str(config["end"]),
        files=files,
        output=output,
    )
