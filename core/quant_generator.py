def _safe_slug(text: str) -> str:
    value = re.sub(r"[^A-Za-z0-9_-]+", "_", str(text or "strategy")).strip("_")
    return value[:60] or "strategy"


@dataclass
class QuantProject:
    path: Path
    strategy_name: str
    symbol: str
    start: str
    end: str
    files: list[str]
    output: RunOutput


def _write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _strategy_template() -> str:
    return r'''from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
from akquant import Strategy


ROOT = Path(__file__).resolve().parent.parent
CONFIG = json.loads((ROOT / "config.json").read_text(encoding="utf-8"))


def _to_bool(value) -> bool:
    if isinstance(value, bool):
        return value
    text = str(value).strip().lower()
    return text in ("1", "true", "yes", "y", "是")


class SignalReplayStrategy(Strategy):
    """AKQuant signal replay strategy generated by 股票策略工坊.

    The actual signals were generated by the desktop strategy engine. This
    class reproduces the T+1 execution semantics with AKQuant's execution
    engine: a signal observed on T is submitted after the close and is filled
    by AKQuant on the next bar.
    """

    warmup_period = 1

    def on_start(self):
        self._trade_symbol = CONFIG["symbol"]
        self.subscribe(self._trade_symbol)
        self._lot_size = int(CONFIG.get("lot_size", 100))
        self._position_pct = float(CONFIG.get("position_pct", 0.95))
        signals = pd.read_csv(ROOT / "data" / "signals.csv")
        signals["date"] = pd.to_datetime(signals["date"], errors="coerce").dt.strftime("%Y-%m-%d")
        signals = signals.dropna(subset=["date"])
        for column in ("entry", "exit"):
            signals[column] = signals[column].map(_to_bool) if column in signals.columns else False
        self.signal_map = signals.set_index("date").to_dict("index")
        self.log(f"loaded {len(signals)} signal rows for {self._trade_symbol}")

    def _buy_quantity(self, price: float) -> int:
        try:
            available = float(self.buying_power)
        except Exception:
            account = self.get_account()
            available = float(account.get("free_margin") or account.get("cash") or 0.0)
        if price <= 0 or available <= 0:
            return 0
        quantity = int((available * self._position_pct) / (price * self._lot_size)) * self._lot_size
        return max(quantity, 0)

    def on_bar(self, bar):
        position = float(self.get_position(bar.symbol) or 0.0)
        day = self.format_time(bar.timestamp, "%Y-%m-%d")
        signal = self.signal_map.get(day)
        if signal is None:
            return
        if bool(signal.get("entry")) and position <= 0:
            quantity = self._buy_quantity(float(bar.close))
            if quantity > 0:
                self.buy(symbol=bar.symbol, quantity=quantity, tag="signal_entry")
                self.log(f"entry {day} {quantity} @ {float(bar.close):.3f}")
        elif bool(signal.get("exit")) and position > 0:
            self.close_position(bar.symbol)
            self.log(f"exit {day} @ {float(bar.close):.3f}")
'''


def _backtest_template() -> str:
    return r'''from __future__ import annotations

import argparse
import json
from pathlib import Path

import akquant
import pandas as pd

from quant_app.strategy import CONFIG, ROOT, SignalReplayStrategy


def load_bars() -> pd.DataFrame:
    bars = pd.read_csv(ROOT / "data" / "bars.csv")
    bars["date"] = pd.to_datetime(bars["date"], errors="coerce")
    bars = bars.dropna(subset=["date"]).drop_duplicates("date").sort_values("date").reset_index(drop=True)
    bars["symbol"] = CONFIG["symbol"]
    return bars


def check() -> None:
    bars = load_bars()
    signals = pd.read_csv(ROOT / "data" / "signals.csv")
    print("AKQuant project check")
    print("  strategy:", CONFIG.get("strategy", {}).get("name", ""))
    print("  symbol:", CONFIG["symbol"])
    print("  bars:", len(bars), bars["date"].min(), "~", bars["date"].max())
    print("  signals:", len(signals))
    print("  akquant:", getattr(akquant, "__version__", "unknown"))
    if bars.empty:
        raise SystemExit("bars.csv 没有有效行情")
    if signals.empty:
        raise SystemExit("signals.csv 没有信号")


def main() -> None:
    parser = argparse.ArgumentParser(description="AKQuant signal replay backtest")
    parser.add_argument("--check", action="store_true", help="只检查数据与依赖，不运行回测")
    parser.add_argument("--no-progress", action="store_true", help="关闭进度条")
    args = parser.parse_args()
    if args.check:
        check()
        return
    bars = load_bars()
    print(f"启动 AKQuant 回测: {CONFIG['symbol']} · {len(bars)} 根 K 线")
    result = akquant.run_backtest(
        data=bars,
        strategy=SignalReplayStrategy,
        symbols=CONFIG["symbol"],
        initial_cash=float(CONFIG.get("initial_cash", 100000.0)),
        commission_rate=float(CONFIG.get("commission_rate", 0.00025)),
        stamp_tax_rate=float(CONFIG.get("stamp_tax_rate", 0.0005)),
        transfer_fee_rate=float(CONFIG.get("transfer_fee_rate", 0.00001)),
        min_commission=float(CONFIG.get("min_commission", 5.0)),
        lot_size=int(CONFIG.get("lot_size", 100)),
        t_plus_one=True,
        show_progress=not args.no_progress,
        warmup_period=1,
    )
    print(result)
    output = ROOT / "output"
    output.mkdir(parents=True, exist_ok=True)
    (output / "backtest_result.txt").write_text(str(result), encoding="utf-8")
    print("结果已写入", output / "backtest_result.txt")


if __name__ == "__main__":
    main()
'''


